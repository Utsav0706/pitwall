"""reports/compare.md: every router, two ways.

1. Routing: Pitwall's own metrics from MLflow (accuracy, under/over-routing, pass rate).
2. End to end: quality and cost of the answers each router's picks would have bought,
   from Gearbox's free offline replay (stored answers and judge scores, no API calls).
   Gearbox is called through its own CLI and venv, never imported: the repos stay apart.
"""

from __future__ import annotations

import json
import platform
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from pitwall.metrics import TIERS
from pitwall.tracking import list_runs

KINDS = ("reference", "baseline", "finetune")
# Same picks as Gearbox v3 (the M2 sanity run); kept in MLflow, left out of the report.
SKIP = {"lr-full-gearbox-settings"}


def latest_runs() -> list[dict[str, Any]]:
    """Newest run per name, for the kinds the report shows."""
    seen: dict[str, dict[str, Any]] = {}
    for r in list_runs():  # newest first
        if r["tags"].get("kind") in KINDS and r["name"] not in SKIP and r["name"] not in seen:
            seen[r["name"]] = r
    order = {k: i for i, k in enumerate(KINDS)}
    return sorted(seen.values(), key=lambda r: (order[r["tags"]["kind"]], r["name"]))


def gearbox_python(gearbox_dir: Path) -> Path:
    sub = "Scripts/python.exe" if platform.system() == "Windows" else "bin/python"
    path = gearbox_dir / ".venv" / sub
    if not path.exists():
        raise FileNotFoundError(f"Gearbox's venv not found at {path} (set GEARBOX_DIR)")
    return path


def replay_command(gearbox_dir: Path, predictions: Path, out: Path) -> list[str]:
    return [
        str(gearbox_python(gearbox_dir)),
        "-m",
        "gearbox.eval",
        "offline",
        "--predictions",
        str(predictions.resolve()),
        "--out",
        str(out.resolve()),
    ]


def gearbox_replay(
    gearbox_dir: Path, gearbox_predictions: Path, ours: dict[str, str]
) -> dict[str, Any]:
    """Gearbox's replay results for its own routers plus ours ({router: predictions jsonl})."""
    with tempfile.TemporaryDirectory() as tmp:
        combined = Path(tmp) / "predictions.jsonl"
        text = gearbox_predictions.read_text(encoding="utf-8")
        combined.write_text(text + "".join(ours.values()), encoding="utf-8", newline="\n")
        out = Path(tmp) / "out"
        result = subprocess.run(
            replay_command(gearbox_dir, combined, out),
            cwd=gearbox_dir,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            raise RuntimeError(f"Gearbox replay failed: {result.stderr.strip()[-800:]}")
        return json.loads((out / "eval.json").read_text(encoding="utf-8"))["results"]


def _pct(v: float | None) -> str:
    return "-" if v is None else f"{100 * v:.1f}%"


def render(runs: list[dict[str, Any]], replay: dict[str, Any]) -> str:
    lines = [
        "# Router comparison",
        "",
        "Generated by `pitwall compare`. All rows use the same 119 test prompts (Gearbox's",
        "test split). Nothing here made a paid API call.",
        "",
        "## Routing",
        "",
        "*Under* = picked a smaller tier than needed (a bad answer); *over* = a bigger one",
        "(wasted money); *pass* = the picked tier's stored answer scored >= 4 with Gearbox's",
        "judge. Latency is the routing decision alone (fine-tune: Ollama on CPU).",
        "",
        "| router | kind | accuracy | under | over | pass | picks S/M/L | hard accuracy "
        "| p50 / p95 |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in runs:
        m = r["metrics"]
        picks = "/".join(str(int(m.get(f"picks.{t}", 0))) for t in TIERS)
        lat = (
            f"{m['latency_p50_ms']:.0f} / {m['latency_p95_ms']:.0f} ms"
            if "latency_p95_ms" in m
            else "-"
        )
        lines.append(
            f"| {r['name']} | {r['tags']['kind']} | {_pct(m.get('accuracy'))} | "
            f"{_pct(m.get('under_rate'))} | {_pct(m.get('over_rate'))} | "
            f"{_pct(m.get('pass_rate'))} | {picks} | {_pct(m.get('hard.accuracy'))} | {lat} |"
        )
    lines += [
        "",
        "## End to end (Gearbox's offline replay)",
        "",
        "Quality = mean judge score as a % of always-L's; cost = the answers at list price",
        "plus routing, as a % of always-L. From `py -m gearbox.eval offline` in Gearbox's",
        "repo, given these routers' predictions. Its pass rates are the same counts as",
        "above, rounded by Gearbox first (e.g. 93/119 shows as 78.1% here, 78.2% above).",
        "",
        "| strategy | quality | pass rate | cost vs L | saved | per 1k requests | picks S/M/L |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r in replay.items():
        p = r["picks"]
        lines.append(
            f"| {name} | {r['quality_pct']:.1f}% | {100 * r['pass_rate']:.1f}% | "
            f"{r['cost_pct']:.1f}% | {r['saved_pct']:.1f}% | "
            f"GBP {r['cost_per_1k_requests_gbp']:.3f} | {p['S']}/{p['M']}/{p['L']} |"
        )
    return "\n".join(lines) + "\n"
