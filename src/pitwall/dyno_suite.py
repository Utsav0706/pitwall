"""The promotion gate's test cases, as a Dyno suite: the 119 test prompts, each with the
tier it needs as the expected answer (exact match). Built by `dvc repro` from
data/derived/test.jsonl, so the gate's cases are versioned like the data they come from.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from pitwall.data import load_pairs, prompt_text

TEST_FILE = Path("data/derived/test.jsonl")
SUITE_FILE = Path("data/dyno/router_suite.yaml")


def build_suite(test_file: Path = TEST_FILE) -> dict:
    cases = [
        {
            "id": pair.id,
            # The prompt as a user sends it; the service adds the template itself.
            "input": prompt_text(pair),
            "expected": pair.label,
            "tags": [pair.part, pair.task_type],
        }
        for pair in load_pairs(test_file)
    ]
    return {
        "name": "pitwall-router",
        "k": 1,  # the router runs at temperature 0: one attempt per case is enough
        "scorers": [{"task_success": {"mode": "exact"}}],
        "cases": cases,
    }


def write_suite(out: Path = SUITE_FILE, test_file: Path = TEST_FILE) -> int:
    suite = build_suite(test_file)
    out.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by `pitwall data dyno-suite` (a dvc.yaml stage). Don't edit.\n"
    text = yaml.safe_dump(suite, sort_keys=False, allow_unicode=True, width=1000)
    out.write_text(header + text, encoding="utf-8", newline="\n")
    return len(suite["cases"])
