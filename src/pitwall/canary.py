"""Canary release through Gearbox: production serves most traffic, the candidate a share.

1. `pitwall canary config` writes runs/gearbox-canary.yaml: Gearbox's own config with
   router v4-finetuned (Pitwall's production model) and canary v4-candidate (Pitwall's
   candidate) on `canary.percent` of requests. Gearbox's repo is not touched; it is
   started with CONFIG_PATH pointing at this file (scripts/gearbox_canary.py).
2. `pitwall canary replay` sends labelled test prompts through Gearbox's OpenAI-style
   API and records which router answered, the tier, the real answer cost and latency
   (Gearbox's x-gearbox-* headers). It stops before spending more than the cap.
3. `pitwall canary report` compares the two sides: tier mix, cost, latency, fail-safes,
   and the pass rate of the tiers picked (free: Gearbox's stored judge scores).

The canary is evidence, not the decision: at 10% the candidate sees few requests. The
decision stays with `pitwall promote` (the Dyno gate on all 119 cases).
"""

from __future__ import annotations

import json
import random
import time
from collections.abc import Iterable
from pathlib import Path
from typing import Any

import httpx
import numpy as np
import yaml

from pitwall.metrics import PASS_SCORE, TIERS

PRODUCTION_ROUTER = "v4-finetuned"
CANDIDATE_ROUTER = "v4-candidate"
CONFIG_OUT = Path("runs/gearbox-canary.yaml")
MAX_TOKENS = 1000  # bounds the cost; quality comes from stored scores, not these answers


def gearbox_canary_config(base: dict[str, Any], percent: float, pitwall_url: str) -> dict:
    config = json.loads(json.dumps(base))  # deep copy
    routing = config.setdefault("routing", {})
    routing["router"] = PRODUCTION_ROUTER
    routing["canary"] = {"router": CANDIDATE_ROUTER, "percent": percent}
    routing["pitwall"] = {"url": pitwall_url, "timeout_s": 5}
    return config


def write_config(
    gearbox_dir: Path, percent: float, pitwall_url: str, out: Path = CONFIG_OUT
) -> Path:
    base = yaml.safe_load((gearbox_dir / "config.yaml").read_text(encoding="utf-8"))
    config = gearbox_canary_config(base, percent, pitwall_url)
    out.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Generated by `pitwall canary config` from Gearbox's config.yaml. Don't edit.\n"
        "# Paths in it are relative to Gearbox's repo, where Gearbox runs.\n"
    )
    out.write_text(header + yaml.safe_dump(config, sort_keys=False), encoding="utf-8", newline="\n")
    return out.resolve()


def pick_prompts(pairs: Iterable[Any], n: int, seed: int) -> list[tuple[str, str]]:
    """(id, prompt text) for n prompts, in a seeded random order."""
    items = [(p.id, next(m["content"] for m in p.messages if m["role"] == "user")) for p in pairs]
    random.Random(seed).shuffle(items)
    return items[:n]


def replay(
    client: httpx.Client,
    prompts: list[tuple[str, str]],
    cap_gbp: float,
    out: Path,
    progress: Any = None,
) -> tuple[int, float, bool]:
    """(requests sent, GBP spent, stopped by the cap). One JSON row per request in `out`."""
    spent, sent = 0.0, 0
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as f:
        for prompt_id, text in prompts:
            if spent >= cap_gbp:
                return sent, spent, True
            start = time.perf_counter()
            response = client.post(
                "/v1/chat/completions",
                json={
                    "model": "auto",
                    "messages": [{"role": "user", "content": text}],
                    "max_tokens": MAX_TOKENS,
                },
            )
            latency = (time.perf_counter() - start) * 1000
            h = response.headers
            cost = float(h.get("x-gearbox-cost", 0.0))
            row = {
                "id": prompt_id,
                "status": response.status_code,
                "router": h.get("x-gearbox-router", ""),
                "tier": h.get("x-gearbox-tier", ""),
                "cost_gbp": cost,
                "latency_ms": round(latency, 1),
                "reason": h.get("x-gearbox-reason", ""),
                "request_id": h.get("x-request-id", ""),
            }
            f.write(json.dumps(row) + "\n")
            spent += cost
            sent += 1
            if progress:
                progress(sent, len(prompts), spent)
    return sent, spent, False


def read_rows(path: Path) -> list[dict[str, Any]]:
    with path.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def summarise(rows: list[dict[str, Any]], scores: dict[str, dict[str, int]]) -> dict[str, dict]:
    """Per router: requests, share, tier mix, pass rate, cost, latency, fail-safes."""
    ok = [r for r in rows if r["status"] == 200]
    out: dict[str, dict] = {}
    for router in sorted({r["router"] for r in ok}):
        group = [r for r in ok if r["router"] == router]
        lat = np.asarray([r["latency_ms"] for r in group])
        judged = [r for r in group if r["id"] in scores and r["tier"] in TIERS]
        out[router] = {
            "requests": len(group),
            "share": len(group) / len(ok),
            "picks": {t: sum(r["tier"] == t for r in group) for t in TIERS},
            "pass_rate": (
                sum(scores[r["id"]].get(r["tier"], 0) >= PASS_SCORE for r in judged) / len(judged)
                if judged
                else None
            ),
            "cost_gbp": round(sum(r["cost_gbp"] for r in group), 6),
            "cost_per_request_gbp": round(sum(r["cost_gbp"] for r in group) / len(group), 6),
            "latency_p50_ms": round(float(np.percentile(lat, 50)), 1),
            "latency_p95_ms": round(float(np.percentile(lat, 95)), 1),
            "fail_safe": sum("pitwall unavailable" in r["reason"] for r in group),
            "versions": sorted({_version(r["reason"]) for r in group} - {""}),
        }
    return out


def _version(reason: str) -> str:
    # "pitwall v1: ft: ..." -> "v1"
    return (
        reason.split(":", 1)[0].removeprefix("pitwall ").strip()
        if reason.startswith("pitwall v")
        else ""
    )


def render(summary: dict[str, dict], errors: int) -> str:
    lines = [
        f"{'router':<14} {'n':>4} {'share':>6} {'S/M/L':>9} {'pass':>6} {'GBP/req':>9} "
        f"{'p50':>7} {'p95':>7} {'fail-safe':>9}  versions",
    ]
    for router, s in summary.items():
        picks = "/".join(str(s["picks"][t]) for t in TIERS)
        pass_rate = "-" if s["pass_rate"] is None else f"{100 * s['pass_rate']:.0f}%"
        lines.append(
            f"{router:<14} {s['requests']:>4} {100 * s['share']:>5.0f}% {picks:>9} {pass_rate:>6} "
            f"{s['cost_per_request_gbp']:>9.5f} {s['latency_p50_ms']:>6.0f}ms "
            f"{s['latency_p95_ms']:>6.0f}ms {s['fail_safe']:>9}  {','.join(s['versions'])}"
        )
    if errors:
        lines.append(f"{errors} requests failed (non-200)")
    return "\n".join(lines)
